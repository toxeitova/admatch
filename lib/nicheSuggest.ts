/** До `limit` ниш, у которых больше всего совпадений с описанием. */
export function suggestNiches(text: string, limit = 2): Niche[] {
  // Ключ должен стоять в начале слова: «бар» не находится внутри «барбершоп», «ент» внутри «центр».
  const s = ` ${text.toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я0-9]+/g, " ")} `;
  if (s.trim().length < 3) return [];
  return (Object.entries(KEYWORDS) as [Niche, string[]][])
    .map(([n, words]) => [n, words.filter((w) => s.includes(" " + w.replace(/ё/g, "е"))).length] as const)
    .filter(([, hits]) => hits > 0)
    .sort((a, b) => b[1] - a[1])
    .slice(0, limit)
    .map(([n]) => n);
}
